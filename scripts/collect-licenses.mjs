async function collect() {
  const pkg = JSON.parse(await readFile('package.json', 'utf8'));
  const names = new Set([
    ...Object.keys(pkg.dependencies ?? {}),
    ...Object.keys(pkg.devDependencies ?? {}),
  ]);
  const rows = [];
  for (const name of [...names].sort()) {
    let meta;
    try {
      meta = JSON.parse(await readFile(path.join('node_modules', name, 'package.json'), 'utf8'));
    } catch {
      rows.push({ name, version: 'unknown', licence: 'unknown', use: USES[name] ?? '', missing: true });
      continue;
    }
    const licence =
      typeof meta.license === 'string'
        ? meta.license
        : meta.license?.type ?? (Array.isArray(meta.licenses) ? meta.licenses.map((l) => l.type).join(' / ') : 'unknown');
    rows.push({
      name,
      version: meta.version ?? 'unknown',
      licence,
      use: USES[name] ?? '',
      homepage: meta.homepage ?? (meta.repository?.url ?? '').replace(/^git\+/, ''),
    });
  }
  return rows;
}

const esc = (v) => String(v ?? '').replace(/\|/g, '\\|');

const rows = await collect();
const missing = rows.filter((r) => r.missing);
const direct = rows.filter((r) => !r.missing);

